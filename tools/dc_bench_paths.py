#!/usr/bin/env python3
"""Fly-through routes for the benchmark tour (make DC_PROF_BENCH=1), from the level data.

    tools/dc_bench_paths.py > src/game/dc_bench_paths.h

For each level, the positions of the objects in its first area: its macro and special objects, and
for a level with one area its level script's OBJECT lines too (in a level with more areas those
may belong to another). From Mario's start, farthest-point sampling picks POINTS of them, spread
over the area; they are visited nearest first. game_init.c flies Mario along the route in the
debug free-move action, through walls, HEIGHT above each point.
"""
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
POINTS = 12
HEIGHT = 150

POS = r"/\*pos\*/\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)"


def level_numbers():
    out, n = {}, 0
    for line in (ROOT / "levels/level_defines.h").read_text().splitlines():
        m = re.match(r"\s*(DEFINE_LEVEL|STUB_LEVEL)\((.*)\)", line)
        if not m:
            continue
        n += 1
        args = [a.strip() for a in m[2].split(",")]
        if m[1] == "DEFINE_LEVEL":
            out[args[3]] = (n, args[1])
    return out


def route(level):
    script = (ROOT / f"levels/{level}/script.c").read_text()
    start = re.search(r"MARIO_POS\(/\*area\*/\s*1,\s*/\*yaw\*/\s*-?\d+,\s*" + POS, script)
    if not start:
        return None
    start = tuple(int(v) for v in start.groups())
    points = []
    for f in (ROOT / f"levels/{level}/areas/1").glob("*.c"):
        src = f.read_text()
        points += [tuple(int(v) for v in m) for m in re.findall(r"(?:MACRO|SPECIAL)_OBJECT\w*\([^)]*?" + POS, src)]
    if len(re.findall(r"\bAREA\(", script)) == 1:
        points += [tuple(int(v) for v in m) for m in re.findall(r"\bOBJECT\w*\([^)]*?" + POS, script)]
    points = sorted(set(points))
    if not points:
        return None
    chosen = [start]
    while len(chosen) < POINTS + 1 and len(chosen) < len(points) + 1:
        far = max(points, key=lambda p: min(math.dist(p, c) for c in chosen))
        if min(math.dist(far, c) for c in chosen) < 300:
            break
        chosen.append(far)
    rest, path = chosen[1:], [start]
    while rest:
        nxt = min(rest, key=lambda p: math.dist(p, path[-1]))
        rest.remove(nxt)
        path.append(nxt)
    return [(x, y + HEIGHT, z) for x, y, z in path]


def main():
    print("/* Generated by tools/dc_bench_paths.py: the benchmark tour's fly-through routes. */")
    rows = []
    for folder, (number, name) in sorted(level_numbers().items(), key=lambda kv: kv[1][0]):
        path = route(folder) if (ROOT / f"levels/{folder}/areas/1").is_dir() else None
        if not path:
            continue
        pts = ", ".join(f"{{ {x}, {y}, {z} }}" for x, y, z in path)
        print(f"static const s16 sBenchPath_{folder}[][3] = {{ {pts} }};")
        rows.append(f"    {{ {name}, ARRAY_COUNT(sBenchPath_{folder}), sBenchPath_{folder} }},")
    print("static const struct { s16 level; u8 count; const s16 (*points)[3]; } sBenchPaths[] = {")
    print("\n".join(rows))
    print("};")


if __name__ == "__main__":
    main()
